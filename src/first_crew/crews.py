"""Crew Factory: one mini-crew per stage of the review-prediction pipeline.

The Flow pre-fetches user / item records via data_store.py (primary-key lookup)
and injects them into the task descriptions as JSON strings.

When RAG_ENABLED=1 in .env, we additionally mount a semantic-search tool over
the historical-reviews ChromaDB collection. This lets the Item Analyst surface what other reviewers have actually said about
similar businesses — context the dict lookup cannot provide.

The pre-built index lives at workspace-root/chroma_index/chroma.sqlite3 (~4.7 GB).
"""

