def _create_rag_tool(collection_name: str, name: str, description: str):
    """Smart-cache JSONSearchTool factory (mirrors the reference create_rag_tool).

    Probes chroma.sqlite3 directly with sqlite3 to confirm the collection
    exists, then constructs the tool WITHOUT a json_path so the agent cannot
    accidentally trigger a 3-hour re-indexing loop. The tool's args_schema is
    swapped for the Fixed variant which hides json_path from the LLM.
    """
    from crewai_tools import JSONSearchTool
    from crewai_tools.tools.json_search_tool.json_search_tool import (
        FixedJSONSearchToolSchema,
    )

    db_file = _CREWAI_STORAGE / "chroma.sqlite3"
    collection_exists = False
    if db_file.exists():
        try:
            conn = sqlite3.connect(str(db_file))
            cur = conn.cursor()
            cur.execute(
                "SELECT id FROM collections WHERE name = ?", (collection_name,)
            )
            collection_exists = cur.fetchone() is not None
            conn.close()
        except Exception as exc:
            print(f"[crews] sqlite check failed for {collection_name}: {exc}")

    if collection_exists:
        tool = JSONSearchTool(collection_name=collection_name, config=_RAG_CONFIG)
        tool.args_schema = FixedJSONSearchToolSchema
        print(f"[crews] RAG tool '{name}' loaded from cache: {collection_name}")
    else:
        # Fall back: would trigger a multi-hour rebuild. We refuse rather than
        # silently start indexing — chroma_index is required.
        raise RuntimeError(
            f"Collection {collection_name!r} not found in {db_file}. "
            "The chroma_index folder must be present at "
            f"{_CREWAI_STORAGE}. We refuse to trigger a multi-hour rebuild."
        )

    tool.name = name
    tool.description = description
    return tool


