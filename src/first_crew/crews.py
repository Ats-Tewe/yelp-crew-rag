def _build_crew(
    agent_cfg: dict,
    task_cfg: dict,
    tools: list | None = None,
    allow_delegation: bool = False,
    max_iter: int = 15,
) -> Crew:
    agent = Agent(
        config=agent_cfg,
        tools=tools or [],
        llm=llm,
        verbose=True,
        allow_delegation=allow_delegation,
        max_iter=max_iter,
    )
    task = Task(config=task_cfg, agent=agent)
    crew_kwargs: dict = {
        "agents": [agent],
        "tasks": [task],
        "process": Process.sequential,
        "verbose": True,
    }
    if _eda_knowledge_source is not None:
        crew_kwargs["knowledge_sources"] = [_eda_knowledge_source]
        crew_kwargs["embedder"] = _EMBEDDER_SPEC
    return Crew(**crew_kwargs)


def user_profiling_crew() -> Crew:
    return _build_crew(_AGENTS["user_profiler"], _TASKS["analyze_user_task_flow"])


def item_profiling_crew() -> Crew:
    # When RAG is on, mount the review-search tool. The task variant
    # (analyze_item_task_flow_rag) explicitly invites the agent to use it
    # if the item record is sparse.
    if _RAG_ENABLED and _review_search_tool is not None:
        return _build_crew(
            _AGENTS["item_analyst"],
            _TASKS["analyze_item_task_flow_rag"],
            tools=[_review_search_tool],
        )
    return _build_crew(_AGENTS["item_analyst"], _TASKS["analyze_item_task_flow"])


def review_prediction_crew() -> Crew:
    return _build_crew(_AGENTS["prediction_modeler"], _TASKS["predict_review_task_flow"])


def _item_tools() -> list:
    return [_review_search_tool] if (_RAG_ENABLED and _review_search_tool) else []


def _calibrator_tools() -> list:
    return [t for t in (_review_search_tool, _user_search_tool) if t is not None]


def _make_agent(config_key: str, *, tools: list, delegate: bool, max_iter: int) -> Agent:
    return Agent(
        config=_AGENTS[config_key], tools=tools, llm=llm,
        allow_delegation=delegate, verbose=True, max_iter=max_iter,
    )


def _attach_knowledge(crew_kwargs: dict) -> dict:
    if _eda_knowledge_source is not None:
        crew_kwargs["knowledge_sources"] = [_eda_knowledge_source]
        crew_kwargs["embedder"] = _EMBEDDER_SPEC
    return crew_kwargs


def pattern2_collaborative_crew() -> Crew:
    """Lab Task 1 — Process.sequential Pattern 2 (Collaborative Single Task).

    One task, four agents. Prediction Modeler (primary) owns the task with
    delegation enabled; the three specialists sit as peers with delegation
    disabled. Hub-and-spoke topology from the professor's PDF (Pattern B).
    """
    primary = _make_agent("prediction_modeler", tools=[], delegate=True, max_iter=25)
    peers = [
        _make_agent("user_profiler", tools=[], delegate=False, max_iter=10),
        _make_agent("item_analyst", tools=_item_tools(), delegate=False, max_iter=10),
        _make_agent("calibrator", tools=_calibrator_tools(), delegate=False, max_iter=15),
    ]
    task = Task(config=_TASKS["collaborative_predict_task"], agent=primary)
    return Crew(**_attach_knowledge({
        "agents": [primary] + peers,
        "tasks": [task],
        "process": Process.sequential,
        "verbose": True,
    }))


def hierarchical_predict_crew() -> Crew:
    """Lab Task 2 — Process.hierarchical crew with an explicit Manager Agent.

    The Manager receives the task and routes sub-tasks to four worker
    specialists. Workers have delegation disabled; the Manager delegates AND
    validates each result.
    """
    manager = _make_agent(
        "review_prediction_manager", tools=[], delegate=True, max_iter=30
    )
    workers = [
        _make_agent("user_profiler", tools=[], delegate=False, max_iter=10),
        _make_agent("item_analyst", tools=_item_tools(), delegate=False, max_iter=10),
        _make_agent("calibrator", tools=_calibrator_tools(), delegate=False, max_iter=15),
        _make_agent("prediction_modeler", tools=[], delegate=False, max_iter=10),
    ]
    # Task has NO agent — the manager routes. Build from fields directly so
    # the YAML's `agent: prediction_modeler` (for Pattern-2 reuse) doesn't
    # confuse pydantic.
    _t = _TASKS["collaborative_predict_task"]
    task = Task(description=_t["description"], expected_output=_t["expected_output"])

    return Crew(**_attach_knowledge({
        "agents": workers,
        "tasks": [task],
        "manager_agent": manager,
        "process": Process.hierarchical,
        "verbose": True,
    }))


def calibrator_crew() -> Crew:
    """Lab Task 4 — Calibrator agent wrapped as a one-task mini-Crew.

    DESIGN NOTE: Originally we mounted search_historical_reviews and
    search_user_profiles on this agent so it could semantically retrieve
    the user's extreme reviews at inference time. That approach failed
    because the agent consistently emitted `{"query": "..."}` as its
    Final Answer instead of as a tool call — a CrewAI parsing issue we
    could not resolve with prompt tuning (see 2026-04-23 session log).

    Current design: the Flow pre-computes the user's top-3 negative and
    top-3 positive past reviews via `get_user_extreme_reviews` (simple
    deterministic sort by |stars − average|) and injects them into the
    task description as JSON. The Calibrator agent just classifies the
    user, picks quotes, and writes the calibration report. No tool calls,
    no parsing surprises, reproducibility restored.
    """
    return _build_crew(
        _AGENTS["calibrator"],
        _TASKS["calibrate_user_task_flow"],
        tools=[],  # no tools — inputs are pre-computed and injected
        allow_delegation=False,
        max_iter=10,
    )
